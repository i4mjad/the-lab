#!/usr/bin/env node

import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import process from "node:process";

const root = resolve(import.meta.dirname, "..");
const catalogPath = resolve(root, "roles/catalog.json");
const checksumsPath = resolve(root, "generated/role-checksums.json");
const check = process.argv.includes("--check");

const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const read = (path) => readFile(path, "utf8");
const generatedHeader = (sourceHash) =>
  `<!-- GENERATED by scripts/generate-role-adapters.mjs; source-sha256: ${sourceHash}. DO NOT EDIT. -->`;

function claudeAdapter(role, body, sourceHash) {
  const permission = role.sandboxMode === "read-only" ? "permissionMode: plan\n" : "";
  return `---\nname: ${role.id}\ndescription: ${role.description}\ntools: ${role.claudeTools}\n${permission}---\n\n${generatedHeader(sourceHash)}\n\n${body.trim()}\n`;
}

function tomlString(value) {
  return JSON.stringify(value);
}

function codexAdapter(role, body, sourceHash) {
  if (body.includes("'''")) throw new Error(`${role.source} contains unsupported TOML delimiter`);
  const lines = [
    `# GENERATED by scripts/generate-role-adapters.mjs; source-sha256: ${sourceHash}. DO NOT EDIT.`,
    `name = ${tomlString(role.id)}`,
    `description = ${tomlString(role.description)}`,
    `sandbox_mode = ${tomlString(role.sandboxMode)}`,
    `developer_instructions = '''`,
    body.trim(),
    `'''`,
    ``,
    `[shell_environment_policy]`,
    `set = { THE_LAB_ROLE = ${tomlString(role.id)} }`
  ];

  if (role.id === "mobile-qa") {
    lines.push(
      ``,
      `[mcp_servers.mobile-mcp]`,
      `command = "npx"`,
      `args = ["-y", "@mobilenext/mobile-mcp@1.0.2"]`,
      `required = true`,
      `enabled_tools = [`,
      `  "mobile_list_available_devices",`,
      `  "mobile_get_screen_size",`,
      `  "mobile_get_orientation",`,
      `  "mobile_take_screenshot",`,
      `  "mobile_save_screenshot",`,
      `  "mobile_list_elements_on_screen",`,
      `  "mobile_click_on_screen_at_coordinates",`,
      `  "mobile_double_tap_on_screen",`,
      `  "mobile_long_press_on_screen_at_coordinates",`,
      `  "mobile_swipe_on_screen",`,
      `  "mobile_type_keys"`,
      `]`,
      `env = { MOBILEMCP_DISABLE_TELEMETRY = "1" }`
    );
  }

  return `${lines.join("\n")}\n`;
}

async function emit(path, content) {
  if (check) {
    let actual;
    try {
      actual = await read(path);
    } catch {
      throw new Error(`missing generated adapter: ${path.slice(root.length + 1)}`);
    }
    if (actual !== content) throw new Error(`generated adapter drift: ${path.slice(root.length + 1)}`);
    return;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}

const catalogText = await read(catalogPath);
const catalog = JSON.parse(catalogText);
if (catalog.schemaVersion !== 1 || !Array.isArray(catalog.roles)) throw new Error("invalid role catalog");

const ids = new Set();
const metadata = { schemaVersion: 1, catalogSha256: sha256(catalogText), roles: {} };
for (const role of catalog.roles) {
  if (!role.id || ids.has(role.id)) throw new Error(`duplicate or empty role id: ${role.id ?? "<empty>"}`);
  ids.add(role.id);
  const body = await read(resolve(root, role.source));
  const sourceHash = sha256(body);
  const claude = claudeAdapter(role, body, sourceHash);
  const codex = codexAdapter(role, body, sourceHash);
  const claudePath = resolve(root, `agents/${role.id}.md`);
  const codexPath = resolve(root, `.codex/agents/${role.id}.toml`);
  await emit(claudePath, claude);
  await emit(codexPath, codex);
  metadata.roles[role.id] = {
    source: role.source,
    sourceSha256: sourceHash,
    claudeSha256: sha256(claude),
    codexSha256: sha256(codex)
  };
}

const checksums = `${JSON.stringify(metadata, null, 2)}\n`;
await emit(checksumsPath, checksums);
if (!check) process.stdout.write(`generated ${catalog.roles.length} Claude and Codex role adapters\n`);
